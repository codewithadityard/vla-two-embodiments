"""One model end to end (Kaggle, GPU): train for the fixed step count S, save the final checkpoint,
evaluate that final checkpoint closed-loop on LIBERO-Goal. No checkpoint is ever chosen by eval results.

  python -m scripts.train_eval configs/runs/A_s0.yaml

Needs the attached datasets libero-goal-smolvlm2-cache and libero-goal-lowdim.
Writes results/eval/<name>.csv and results/runs/<name>.md; checkpoint + GIFs go to outputs/<name>/.
Exits 1 if any check fails.
"""
import gc
import sys
import time
from pathlib import Path

import torch

from minivla.backbone import Backbone
from minivla.config import load_config, seed_everything
from minivla.eval_libero import Policy, evaluate, summary_lines
from minivla.train import prepare, setup_determinism, train, zero_baseline_l1


def main(run_path):
    setup_determinism()
    cfg = load_config(run_path)
    name, steps = cfg["name"], cfg["train"]["steps"]
    seed_everything(cfg["seed"])
    out = Path("outputs") / name
    checks = []

    def check(n, ok, detail=""):
        checks.append((n, bool(ok), detail))
        print("PASS" if ok else "FAIL", n, detail, flush=True)

    # train
    d, train_rows, val_rows, stats = prepare(cfg)
    baseline = zero_baseline_l1(d, val_rows)
    t0 = time.time()
    expert, head, hist = train(cfg, d, train_rows, val_rows, steps, out / "metrics.csv", seed=cfg["seed"])
    train_min = (time.time() - t0) / 60
    check("trained exactly S steps; final checkpoint is the one evaluated", hist[-1][0] == steps, f"S = {steps}")
    check("final val L1 < mean-chunk baseline", hist[-1][2] < baseline, f"{hist[-1][2]:.4f} vs {baseline:.4f}")
    torch.save({"expert": expert.state_dict(), "stats": stats, "cfg": cfg, "cache_meta": d.meta, "step": steps},
               out / "final.pt")
    n_prefix, n_text, in_ram, load_min = d.n_prefix, d.n_text, d.in_ram, d.load_min
    del d
    gc.collect()

    # evaluate the final checkpoint
    bb = Backbone(cfg["backbone"]["name"], cfg["backbone"]["revision"], cfg["backbone"]["num_layers"])
    check("online backbone prefix length == cache prefix length", bb.prefix_len == n_prefix,
          f"{bb.prefix_len} vs {n_prefix}")
    rows = evaluate(cfg, Policy(cfg, expert, head, bb, n_text, stats), name,
                    Path("results/eval") / f"{name}.csv", out / "videos")
    n_expected = 10 * cfg["eval"]["episodes_per_task"]
    check("every eval episode ran", len(rows) == n_expected, f"{len(rows)} / {n_expected}")

    # report
    L = [f"# Run {name}", "", f"Generated by `python -m scripts.train_eval {run_path}`. Every number is measured in this run.",
         "", f"- Config: head `{cfg['head']}`, language {cfg['use_language']}, seed {cfg['seed']}, S = {steps} steps, "
         f"batch {cfg['train']['batch']}; GPU {torch.cuda.get_device_name(0)}",
         f"- Training: {train_min:.1f} min ({hist[-1][4]:.4f} s/step); cache in RAM {in_ram} (load {load_min:.1f} min)",
         f"- Val L1 (normalized, fixed subset) at the final step: {hist[-1][2]:.4f}; mean-chunk baseline {baseline:.4f}",
         f"- Eval: {cfg['eval']['episodes_per_task']} episodes per task, eval_seed {cfg['eval']['eval_seed']}, "
         f"n_action_steps {cfg['eval']['n_action_steps']}, final checkpoint only", "", "## Checks", "",
         "| Check | Result | Detail |", "|---|---|---|"]
    L += [f"| {n} | {'PASS' if ok else '**FAIL**'} | {dt} |" for n, ok, dt in checks]
    L += ["", "## Validation L1 during training", "", "| Step | Val L1 |", "|---|---|"]
    L += [f"| {r[0]} | {r[2]:.4f} |" for r in hist if r[2] != ""]
    L += ["", "## Closed-loop eval (final checkpoint)", ""] + summary_lines(rows)
    Path("results/runs").mkdir(parents=True, exist_ok=True)
    Path(f"results/runs/{name}.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))
    failed = [n for n, ok, _ in checks if not ok]
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main(sys.argv[1])
