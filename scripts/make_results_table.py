"""M6: results/eval/*.csv -> results/ablation_table.md (success rates with Wilson 95 % CIs). Laptop, NumPy only.

  python -m scripts.make_results_table
"""
import csv
from collections import defaultdict
from pathlib import Path

from minivla.stats import wilson

EVAL_DIR = Path("results/eval")
OUT = Path("results/ablation_table.md")
CONFIGS = {"A": "language + flow matching", "B": "no language + flow matching", "C": "language + L1 regression"}


def load_rows():
    rows = []
    for path in sorted(EVAL_DIR.glob("*.csv")):
        with open(path) as f:
            rows += [dict(r, success=int(r["success"])) for r in csv.DictReader(f)]
    return rows


def rate(rows):
    k, n = sum(r["success"] for r in rows), len(rows)
    lo, hi = wilson(k, n)
    return f"{k}/{n}", f"{100 * k / n:.1f}", f"{100 * lo:.1f}–{100 * hi:.1f}"


def table(rows, groups, label):
    L = [f"| {label} | Successes | Rate (%) | Wilson 95 % CI (%) |", "|---|---|---|---|"]
    for key, rr in groups.items():
        L.append(f"| {key} | " + " | ".join(rate(rr)) + " |")
    return L


def main():
    rows = load_rows()
    by_config, by_model, by_task = defaultdict(list), defaultdict(list), defaultdict(lambda: defaultdict(list))
    for r in rows:
        cfg = r["run"].split("_")[0]
        by_config[f"{cfg}: {CONFIGS.get(cfg, '?')}"].append(r)
        by_model[r["run"]].append(r)
        by_task[f"{r['env_task']}: {r['instruction']}"][cfg].append(r)
    L = ["# Ablation results (LIBERO-Goal, closed loop, final checkpoints)", "",
         "Generated by `python -m scripts.make_results_table` from `results/eval/*.csv`.", "",
         "## Per config (seeds pooled)", ""]
    L += table(rows, dict(sorted(by_config.items())), "Config")
    L += ["", "## Per model", ""] + table(rows, dict(sorted(by_model.items())), "Run")
    cfgs = sorted({r["run"].split("_")[0] for r in rows})
    L += ["", "## Per task (successes per config, seeds pooled)", "", "| Task | " + " | ".join(cfgs) + " |",
          "|---|" + "---|" * len(cfgs)]
    for task, per in sorted(by_task.items(), key=lambda kv: int(kv[0].split(":")[0])):
        L.append(f"| {task} | " + " | ".join(rate(per[c])[0] if per[c] else "–" for c in cfgs) + " |")
    L += ["", "Resolution: at n = 100 and a rate near 50 %, the Wilson 95 % CI is about ±9.6 points "
          "(±13.4 at n = 50), so differences of ~15–20 points may not be resolvable."]
    OUT.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
