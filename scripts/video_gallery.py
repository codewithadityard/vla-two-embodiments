"""Video gallery (Kaggle, GPU): DEMO, NOT PART OF THE REPORTED RESULTS.

  python -m scripts.video_gallery            A_s0 on one episode of each of the 10 tasks (GPU 0) and B_s0 on the
                                             same start state for tasks 0-2 (GPU 1), at once; then the gallery page
  python -m scripts.video_gallery A_s0       one model only (what the two child processes run)

Uses the saved final checkpoints (attach the Kaggle runs that trained A_s0 and B_s0). Start state GALLERY_EP = 10 is
outside the evaluated start states 0-9, so the gallery cannot be mixed up with the eval. Writes only to
outputs/gallery/ (CSV, GIFs) and results/video_gallery.md; never to results/eval, results/runs or the tables.
"""
import csv
import sys
from pathlib import Path

import torch
from PIL import Image

from minivla.backbone import Backbone
from minivla.config import load_config, seed_everything
from minivla.eval_libero import Policy, evaluate
from minivla.parallel import run_parallel
from minivla.train import find_input, make_expert_and_head, setup_determinism

GALLERY_EP = 10  # init state 10, seed eval_seed + 10
MODELS = {"A_s0": list(range(10)), "B_s0": [0, 1, 2]}  # B: first three tasks (fixed rule, not picked by eye)
OUT = Path("outputs/gallery")
MAX_BYTES = 2_000_000


def shrink(path):
    """Keep a GIF under 2 MB by dropping every other frame (at the same playback speed) until it fits."""
    while path.stat().st_size >= MAX_BYTES:
        im = Image.open(path)
        frames, duration = [], im.info.get("duration", 100)
        try:
            while True:
                frames.append(im.copy())
                im.seek(im.tell() + 1)
        except EOFError:
            pass
        frames = frames[::2]
        frames[0].save(path, save_all=True, append_images=frames[1:], duration=2 * duration, loop=0)


def run_model(name):
    setup_determinism()
    cfg = load_config(f"configs/runs/{name}.yaml")
    seed_everything(cfg["seed"])
    ck = torch.load(find_input(f"{name}/final.pt"), map_location="cuda", weights_only=False)  # our own file
    assert ck["step"] == cfg["train"]["steps"], f"not the final checkpoint: step {ck['step']}"
    meta = ck["cache_meta"]
    expert, head = make_expert_and_head(ck["cfg"], meta["n_prefix"] + meta["n_text"], meta["dim"])
    expert.load_state_dict(ck["expert"])
    expert = expert.to("cuda").eval()
    bb = Backbone(cfg["backbone"]["name"], cfg["backbone"]["revision"], cfg["backbone"]["num_layers"])
    assert bb.prefix_len == meta["n_prefix"], (bb.prefix_len, meta["n_prefix"])
    evaluate(cfg, Policy(cfg, expert, head, bb, meta["n_text"], ck["stats"]), name, OUT / f"{name}.csv",
             OUT / name, tasks=MODELS[name], episodes=[GALLERY_EP])
    for gif in (OUT / name).glob("*.gif"):
        shrink(gif)


def main():
    codes = run_parallel([(name, gpu, ["scripts.video_gallery", name]) for gpu, name in enumerate(MODELS)])
    rows = {}
    for name in MODELS:
        if (OUT / f"{name}.csv").exists():
            with open(OUT / f"{name}.csv") as f:
                rows[name] = {int(r["env_task"]): r for r in csv.DictReader(f)}
    L = ["# Video gallery: demo, not part of reported results", "",
         "**Demo, not part of reported results.** These episodes are not in `results/eval/`, the ablation table or "
         "the README numbers. Generated by `python -m scripts.video_gallery` from the saved final checkpoints.", "",
         f"- Start state {GALLERY_EP} of every task (seed eval_seed + {GALLERY_EP}); the evaluation used start "
         "states 0-9, so these are new episodes.",
         "- A_s0 (language + flow matching) on all 10 tasks; B_s0 (no language) on tasks 0-2 at the same start "
         "state. One episode each: a single episode says nothing about a success rate.",
         f"- Exit codes: {codes}", "", "| Task | Instruction | A_s0 | B_s0 |", "|---|---|---|---|"]

    def cell(name, task):
        r = rows.get(name, {}).get(task)
        if r is None:
            return "–"
        result = "success" if r["success"] == "1" else "fail"
        gif = f"task{task}_ep{GALLERY_EP}_{result}.gif"
        return f"{result} ({r['steps']} steps)<br>![{name} task {task}](../docs/media/gallery/{name}/{gif})"

    for task in MODELS["A_s0"]:
        instr = rows.get("A_s0", {}).get(task, {}).get("instruction", "–")
        L.append(f"| {task} | {instr} | {cell('A_s0', task)} | {cell('B_s0', task)} |")
    sizes = {str(p): p.stat().st_size for p in OUT.rglob("*.gif")}
    L += ["", f"GIFs: {len(sizes)}, largest {max(sizes.values(), default=0) / 1e6:.2f} MB (limit 2 MB)."]
    Path("results").mkdir(exist_ok=True)
    Path("results/video_gallery.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))
    n_ok = sum(len(v) for v in rows.values())
    sys.exit(0 if all(c == 0 for c in codes.values()) and n_ok == 13 and max(sizes.values(), default=0) < MAX_BYTES
             else 1)


if __name__ == "__main__":
    run_model(sys.argv[1]) if len(sys.argv) > 1 else main()
