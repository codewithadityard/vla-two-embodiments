"""CPU-only sanity test of the flow-matching code (no GPU quota): learn a bimodal 2-D distribution.

Data: two clusters, N((-2, 0), 0.25^2 I) and N((+2, 0), 0.25^2 I), half the points each; the empty middle is
|x| < 1 (4 standard deviations from both centers). The model is our ActionExpert (flow=True, chunk 1, action
dim 2; features and state are constant, so only x_t and t carry information) trained with our
FlowMatchingHead.loss; sampling uses FlowMatchingHead.predict, i.e. the same Euler sampler and time
convention as the LIBERO eval (noise at t = 1, 10 steps to t = 0).

Pass: each cluster gets 30-70 % of 1,000 samples, and at most 2 % land in the empty middle.
A sign or time-convention bug sends samples away from the data or collapses them, and fails this.

  python -m scripts.flow_toy      -> results/flow_toy.png, results/flow_toy.md; exit 1 on failure
"""
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import torch  # noqa: E402

from minivla.expert import ActionExpert  # noqa: E402
from minivla.heads import FlowMatchingHead  # noqa: E402
from minivla.train import lr_factor  # noqa: E402

CENTER, STD, MIDDLE = 2.0, 0.25, 1.0
STEPS, BATCH, LR, N_SAMPLES = 4000, 256, 1e-3, 1000


def data(n, g):
    side = torch.randint(0, 2, (n,), generator=g) * 2 - 1
    pts = torch.randn(n, 2, generator=g) * STD
    pts[:, 0] += side * CENTER
    return pts


def main():
    torch.manual_seed(0)
    g = torch.Generator().manual_seed(0)
    expert = ActionExpert(4, 1, state_dim=8, act_dim=2, chunk=1, d=64, layers=2, heads=4, ffn=128, dropout=0.0,
                          flow=True)
    head = FlowMatchingHead(steps=10)
    opt = torch.optim.AdamW(expert.parameters(), lr=LR)
    sched = torch.optim.lr_scheduler.LambdaLR(opt, lambda i: lr_factor(i, 200, STEPS, LR, LR * 0.025))

    def const_inputs(b):  # uninformative conditioning: one zero feature token (real), zero state
        return torch.zeros(b, 1, 4), torch.ones(b, 1, dtype=torch.bool), torch.zeros(b, 8)

    feats, mask, state = const_inputs(BATCH)
    pad = torch.zeros(BATCH, 1, dtype=torch.bool)
    losses = []
    for _ in range(STEPS):
        actions = data(BATCH, g)[:, None]  # [B, chunk=1, 2]
        loss = head.loss(expert, feats, mask, state, actions, pad)
        opt.zero_grad()
        loss.backward()
        opt.step()
        sched.step()
        losses.append(loss.item())
    expert.eval()
    feats, mask, state = const_inputs(N_SAMPLES)
    samples = head.predict(expert, feats, mask, state, generator=torch.Generator().manual_seed(1))[:, 0]
    x = samples[:, 0]
    left, right, middle = (x < -MIDDLE).float().mean().item(), (x > MIDDLE).float().mean().item(), \
        (x.abs() < MIDDLE).float().mean().item()
    near = ((samples - torch.tensor([[CENTER, 0.0]]) * torch.sign(x)[:, None]).norm(dim=1) < 4 * STD).float().mean().item()
    checks = [("left cluster gets 30-70 % of samples", 0.3 <= left <= 0.7, f"{100 * left:.1f} %"),
              ("right cluster gets 30-70 % of samples", 0.3 <= right <= 0.7, f"{100 * right:.1f} %"),
              ("at most 2 % of samples in the empty middle |x| < 1", middle <= 0.02, f"{100 * middle:.1f} %")]

    Path("results").mkdir(exist_ok=True)
    real = data(N_SAMPLES, torch.Generator().manual_seed(2))
    fig, ax = plt.subplots(figsize=(6, 4))
    ax.scatter(real[:, 0], real[:, 1], s=4, alpha=0.4, label="training data")
    ax.scatter(samples[:, 0], samples[:, 1], s=4, alpha=0.6, label="flow samples (10 Euler steps)")
    ax.axvspan(-MIDDLE, MIDDLE, color="grey", alpha=0.15, label="empty middle")
    ax.set_xlim(-4, 4)
    ax.set_ylim(-2, 2)
    ax.legend(loc="upper center", fontsize=8)
    ax.set_title("Flow-matching head on a bimodal 2-D toy (CPU)")
    fig.tight_layout()
    fig.savefig("results/flow_toy.png", dpi=100)

    L = ["# Flow-matching toy test (CPU)", "", "Generated by `python -m scripts.flow_toy`. Every number is measured "
         "in this run. Plot: `results/flow_toy.png`.", "",
         f"- Data: two clusters at x = ±{CENTER}, std {STD}; {STEPS} steps, batch {BATCH}, peak lr {LR}",
         f"- Train loss: first step {losses[0]:.4f}, mean of last 100 steps {sum(losses[-100:]) / 100:.4f}",
         f"- Samples: {N_SAMPLES}, 10 Euler steps from noise at t = 1 to t = 0; within 4 std of a center: "
         f"{100 * near:.1f} %", "", "| Check | Result | Detail |", "|---|---|---|"]
    L += [f"| {n} | {'PASS' if ok else '**FAIL**'} | {dt} |" for n, ok, dt in checks]
    Path("results/flow_toy.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))
    sys.exit(0 if all(ok for _, ok, _ in checks) else 1)


if __name__ == "__main__":
    main()
