"""Top-up eval (Kaggle, GPU): evaluate a finished model's saved final checkpoint on start states 5-9, so models
evaluated with 5 episodes per task reach the approved 10. Same protocol as scripts/train_eval.py: episode e uses
init state e and seed eval_seed + e, so these are exactly the episodes a 10-episode eval would have run.

  python -m scripts.eval_topup configs/runs/A_s0.yaml

Needs the run's checkpoint attached as an input (the output of the Kaggle run that trained it, which has
outputs/<name>/final.pt). Writes results/eval/<name>_ep5-9.csv and results/runs/<name>_ep5-9.md.
Exits 1 if any check fails.
"""
import sys
from pathlib import Path

import torch

from minivla.backbone import Backbone
from minivla.config import load_config, seed_everything
from minivla.eval_libero import Policy, evaluate, summary_lines
from minivla.train import find_input, make_expert_and_head, setup_determinism

EPISODES = list(range(5, 10))


def main(run_path):
    setup_determinism()
    cfg = load_config(run_path)
    name = cfg["name"]
    seed_everything(cfg["seed"])
    checks = []

    def check(n, ok, detail=""):
        checks.append((n, bool(ok), detail))
        print("PASS" if ok else "FAIL", n, detail, flush=True)

    ckpt_path = find_input(f"{name}/final.pt")
    ck = torch.load(ckpt_path, map_location="cuda", weights_only=False)  # our own file: holds numpy stats
    check("checkpoint is the final one (step == S)", ck["step"] == cfg["train"]["steps"], f"step {ck['step']}")
    same = {k: (ck["cfg"][k], cfg[k]) for k in ["name", "head", "use_language", "seed"]}
    check("checkpoint config matches the run config (name, head, language, seed)",
          all(a == b for a, b in same.values()), str(same))
    meta = ck["cache_meta"]
    expert, head = make_expert_and_head(ck["cfg"], meta["n_prefix"] + meta["n_text"], meta["dim"])
    expert.load_state_dict(ck["expert"])
    expert = expert.to("cuda").eval()
    bb = Backbone(cfg["backbone"]["name"], cfg["backbone"]["revision"], cfg["backbone"]["num_layers"])
    check("online backbone prefix length == cache prefix length", bb.prefix_len == meta["n_prefix"],
          f"{bb.prefix_len} vs {meta['n_prefix']}")
    tag = f"{name}_ep{EPISODES[0]}-{EPISODES[-1]}"
    rows = evaluate(cfg, Policy(cfg, expert, head, bb, meta["n_text"], ck["stats"]), name,
                    Path("results/eval") / f"{tag}.csv", Path("outputs") / name / "videos", episodes=EPISODES)
    check("every top-up episode ran", len(rows) == 10 * len(EPISODES), f"{len(rows)} / {10 * len(EPISODES)}")

    L = [f"# Top-up eval {tag}", "", f"Generated by `python -m scripts.eval_topup {run_path}`. Every number is "
         "measured in this run.", "", f"- Checkpoint: `{ckpt_path}` (final, step {ck['step']}); "
         f"GPU {torch.cuda.get_device_name()}",
         f"- Episodes {EPISODES[0]}-{EPISODES[-1]} of every task (init state e, seed eval_seed + e = "
         f"{cfg['eval']['eval_seed'] + EPISODES[0]}-{cfg['eval']['eval_seed'] + EPISODES[-1]}); "
         f"episodes 0-4 are in `results/runs/{name}.md`", "", "## Checks", "",
         "| Check | Result | Detail |", "|---|---|---|"]
    L += [f"| {n} | {'PASS' if ok else '**FAIL**'} | {dt} |" for n, ok, dt in checks]
    L += ["", "## Closed-loop eval, episodes 5-9 (final checkpoint)", ""] + summary_lines(rows)
    Path("results/runs").mkdir(parents=True, exist_ok=True)
    Path(f"results/runs/{tag}.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))
    sys.exit(1 if any(not ok for _, ok, _ in checks) else 0)


if __name__ == "__main__":
    main(sys.argv[1])
