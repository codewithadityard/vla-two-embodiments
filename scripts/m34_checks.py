"""M3 + M4 in one Kaggle GPU run: torch unit tests, real-feature overfit, determinism, short runs, step count S.

Needs the attached datasets: libero-goal-smolvlm2-cache and libero-goal-lowdim. Writes results/m34_checks.md.
Exits 1 if any check fails.
"""
import copy
import math
import subprocess
import sys
from pathlib import Path

import numpy as np
import torch

from minivla.config import load_config, seed_everything
from minivla.heads import masked_mean
from minivla.train import make_expert_and_head, prepare, setup_determinism, train, zero_baseline_l1

REPORT = Path("results/m34_checks.md")
SHORT_STEPS = 2000


def overfit_real(cfg, d, rows, steps):
    """8 fixed real samples, dropout 0, lr 1e-3: masked L1 of the prediction after `steps` steps."""
    cfg = copy.deepcopy(cfg)
    cfg["model"]["dropout"] = 0.0
    torch.manual_seed(0)
    expert, head = make_expert_and_head(cfg, d.n_prefix + d.n_text, d.dim)
    expert = expert.to(d.device).train()
    opt = torch.optim.AdamW(expert.parameters(), lr=1e-3)
    feats, mask, state, actions, pad = d.batch(rows)
    for _ in range(steps):
        with torch.autocast("cuda", dtype=torch.float16):
            loss = head.loss(expert, feats, mask, state, actions, pad)
        opt.zero_grad()
        loss.backward()
        opt.step()
    expert.eval()
    g = torch.Generator(device=d.device).manual_seed(0)
    with torch.autocast("cuda", dtype=torch.float16):
        pred = head.predict(expert, feats, mask, state, generator=g)
    return masked_mean((pred.float() - actions).abs(), pad).item()


def main():
    setup_determinism()
    cfg_a, cfg_c = load_config("configs/A_flow_lang.yaml"), load_config("configs/C_l1_lang.yaml")
    seed_everything(cfg_a["seed"])
    checks = []

    def check(name, ok, detail=""):
        checks.append((name, bool(ok), detail))
        print("PASS" if ok else "FAIL", name, detail, flush=True)

    # 1. torch unit tests
    p = subprocess.run([sys.executable, "-m", "pytest", "-q", "tests/test_expert.py"], capture_output=True, text=True)
    check("torch unit tests (tests/test_expert.py)", p.returncode == 0, p.stdout.strip().splitlines()[-1])
    if p.returncode != 0:
        print(p.stdout[-3000:])

    # 2. data (A and C both use language, so one loaded cache serves both)
    d, train_rows, val_rows, stats = prepare(cfg_a)
    baseline = zero_baseline_l1(d, val_rows)

    # 3. overfit 8 real samples
    rows8 = np.sort(np.random.default_rng(0).choice(train_rows, 8, replace=False))
    l1_c = overfit_real(cfg_c, d, rows8, 1000)
    l1_a = overfit_real(cfg_a, d, rows8, 3000)
    check("regression head overfits 8 real samples (L1 < 0.02 after 1000 steps)", l1_c < 0.02, f"L1 {l1_c:.4f}")
    check("flow head overfits 8 real samples (10-step sample L1 < 0.05 after 3000 steps)", l1_a < 0.05, f"L1 {l1_a:.4f}")

    # 4. determinism on the GPU: same seed -> identical losses
    h1 = train(cfg_a, d, train_rows, val_rows, 50, "outputs/m34/det1.csv", seed=0, log_every=10)[2]
    h2 = train(cfg_a, d, train_rows, val_rows, 50, "outputs/m34/det2.csv", seed=0, log_every=10)[2]
    same = [r[1] for r in h1] == [r[1] for r in h2]
    check("same seed gives identical training losses on the GPU (50 steps, flow head)", same,
          f"{[round(r[1], 6) for r in h1]} vs {[round(r[1], 6) for r in h2]}" if not same else "")

    # 5. short runs (val every 250 steps)
    results = {}
    for name, cfg in [("C (L1)", cfg_c), ("A (flow)", cfg_a)]:
        cfg = copy.deepcopy(cfg)
        cfg["train"]["val_every"] = 250
        hist = train(cfg, d, train_rows, val_rows, SHORT_STEPS, f"outputs/m34/short_{name[0]}.csv", seed=0)[2]
        results[name] = hist
        final_val = hist[-1][2]
        check(f"{name}: val L1 after {SHORT_STEPS} steps < mean-chunk baseline", final_val < baseline,
              f"val L1 {final_val:.4f} vs baseline {baseline:.4f}")

    # 6. step count S (plan rule: S = min(20000, steps that fit in 60 min), using the slower head)
    s_step = max(h[-1][4] for h in results.values())
    S = min(20000, math.floor(3600 / s_step))
    check("configured train.steps equals the plan rule's S", S == cfg_a["train"]["steps"],
          f"rule S = {S} (slowest head {s_step:.4f} s/step); configured {cfg_a['train']['steps']}")

    # report
    L = ["# M3 + M4 checks (one Kaggle run)", "",
         "Generated by `python -m scripts.m34_checks`. Every number is measured in this run.", "",
         f"- GPU: {torch.cuda.get_device_name(0)}; cache in RAM: {d.in_ram} (needs {d.need_gb:.1f} GB, "
         f"machine has {d.ram_gb:.1f} GB; load {d.load_min:.1f} min)",
         f"- Train / val frames: {len(train_rows)} / {len(val_rows)} (fixed val subset); "
         f"mean-chunk baseline val L1: {baseline:.4f}", "", "## Checks", "",
         "| Check | Result | Detail |", "|---|---|---|"]
    L += [f"| {n} | {'PASS' if ok else '**FAIL**'} | {dt} |" for n, ok, dt in checks]
    for name, hist in results.items():
        L += ["", f"## Short run {name}: {SHORT_STEPS} steps, batch {cfg_a['train']['batch']}", "",
              "| Step | Train loss | Val L1 | LR | s/step |", "|---|---|---|---|---|"]
        L += [f"| {r[0]} | {r[1]:.4f} | {r[2] if r[2] == '' else f'{r[2]:.4f}'} | {r[3]:.2e} | {r[4]:.4f} |" for r in hist]
    L += ["", f"**Step count rule: S = {S}** ({S * s_step / 60:.0f} min per model at {s_step:.4f} s/step).", ""]
    REPORT.parent.mkdir(exist_ok=True)
    REPORT.write_text("\n".join(L) + "\n")
    failed = [n for n, ok, _ in checks if not ok]
    print(f"Checks: {len(checks) - len(failed)}/{len(checks)} PASS")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
