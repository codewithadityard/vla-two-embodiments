"""Wilson score interval for a success rate (NumPy only)."""
import math


def wilson(k: int, n: int, z: float = 1.96):
    """95 % Wilson interval (low, high) for k successes in n trials."""
    if n == 0:
        return 0.0, 1.0
    p = k / n
    denom = 1 + z * z / n
    center = (p + z * z / (2 * n)) / denom
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / denom
    return max(0.0, center - half), min(1.0, center + half)
